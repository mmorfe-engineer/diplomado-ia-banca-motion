#!/usr/bin/env python3
"""Prepare block timing/SRT, then independently validate completed new MP4s.

No existing approved render or report is regenerated by this script.
"""
import argparse
from array import array
import hashlib
import json
import math
from pathlib import Path
import re
import subprocess
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
BLOCKS = {'07-10': ['v7','v8','v9','v10'],
          '11-16': ['v11','v12','v13','v14','v15','v16'],
          '17-21': ['v17_18','v19','v20','silence']}


def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def norm(text):
    text = ''.join(c for c in unicodedata.normalize('NFD',text.lower()) if unicodedata.category(c) != 'Mn')
    text = re.sub(r'chat\s+bot', 'chatbot', text)
    return re.findall(r'\w+', text)


def stamp(t):
    ms=round(t*1000)
    return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'


def decode(path, start, duration):
    return array('f', subprocess.check_output(['ffmpeg','-v','error','-i',str(path),'-ss',str(start),'-t',str(duration),'-vn','-ar','48000','-ac','1','-f','f32le','-']))


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--block',choices=BLOCKS,required=True)
    p.add_argument('--prepare',action='store_true')
    args=p.parse_args()
    words=json.loads((ROOT/'src/locales/diplomado/words.json').read_text())
    voices=json.loads((ROOT/'src/locales/diplomado/voices.json').read_text())
    manifest=json.loads((ROOT/'inputs/voiceover/diplomado-manifest.json').read_text())
    script=json.loads((ROOT/'docs/dialogos_banca.json').read_text())
    preserved=json.loads((ROOT/'out/recuperacion-2026-10-28.json').read_text())['preserved']
    for path,expected in preserved.items():
        assert digest(ROOT/path)==expected, f'Approved asset changed: {path}'
    for spec in manifest:
        assert digest(Path(spec['source']))==spec['sha256']
    scenes=[]; lines=[]; frame=0
    for i,voice in enumerate(BLOCKS[args.block]):
        silent=voice=='silence'
        pre=0 if silent else .6
        tail=0 if silent else (1.2 if voice in ['v10','v16','v20'] else .9)
        frames=math.ceil((pre+voices[voice]+tail)*30-1e-9)
        offset=frame/30+pre
        data=words[voice]
        assert all(0<=s<e<=voices[voice]+1e-6 for _,s,e in data), voice
        assert all(a[1]<=b[1] for a,b in zip(data,data[1:])), voice
        if not silent:
            spec=next(s for s in script if s['id']==(voice[1:] if voice=='v17_18' else f'{int(voice[1:]):02}'))
            assert norm(spec['text'])==norm(' '.join(w[0] for w in data)), (voice,'caption/script mismatch')
            assert not re.search(r'BNC|carné|carnét',' '.join(w[0] for w in data))
        cur=[]
        for text,s,e in data:
            cur.append([text,s+offset,e+offset])
            if (re.search(r'[.,?;:]$',text) and len(cur)>=3) or len(cur)>=7:
                lines.append(cur);cur=[]
        if cur:lines.append(cur)
        scenes.append({'voice':voice,'startFrame':frame,'frames':frames,'voiceStart':offset,'voiceDuration':voices[voice]})
        frame+=frames
    output=ROOT/f'out/revision-{args.block}'
    output.mkdir(exist_ok=True)
    timeline={'frames':frame,'fps':30,'scenes':scenes}
    if args.block=='17-21':
        timeline['visualTransition17_18']={'frame':493,'sourceTime':493/30-.6,'audio':'One continuous original track; no cut, restart or duplicated audio'}
    (output/'timeline.json').write_text(json.dumps(timeline,indent=2)+'\n')
    srt=[]
    for i,line in enumerate(lines):
        end=min(line[-1][2]+.6,lines[i+1][0][1] if i+1<len(lines) else math.inf)
        srt.append(f'{i+1}\n{stamp(line[0][1])} --> {stamp(end)}\n'+ ' '.join(w[0] for w in line)+'\n')
    (output/f'subtitulos-{args.block}.srt').write_text('\n'.join(srt))
    if args.prepare:
        print(f'{args.block}: preflight PASS, {frame} frames; approved assets preserved; SRT exported')
        return
    video=output/f'diplomado-ia-escenas-{args.block}.mp4'
    meta=json.loads(subprocess.check_output(['ffprobe','-v','error','-show_streams','-show_format','-of','json',str(video)]))
    v=next(s for s in meta['streams'] if s['codec_type']=='video')
    a=next(s for s in meta['streams'] if s['codec_type']=='audio')
    assert (v['width'],v['height'],v['r_frame_rate'],v['codec_name'],a['codec_name'])==(1920,1080,'30/1','h264','aac')
    assert int(v['nb_frames'])==frame
    assert abs(float(meta['format']['duration'])-frame/30)<.06
    correlations={}
    for scene in scenes:
        voice=scene['voice']
        if voice=='silence':continue
        wav=ROOT/f'public/voice/diplomado/{voice}.wav'
        spec=next(s for s in manifest if s['id']==(voice[1:] if voice=='v17_18' else f'{int(voice[1:]):02}'))
        samples=lambda p:len(decode(p,0,voices[voice]+1))
        assert abs(samples(wav)-samples(spec['source']))<=1
        correlations[voice]=[]
        for source_at in [min(1,voices[voice]/4),max(0,voices[voice]-4)]:
            ref=decode(wav,source_at,3)
            mix=decode(video,scene['voiceStart']+source_at,3)
            count=min(len(ref),len(mix));ref=ref[:count];mix=mix[:count]
            window=6000
            anchor=max(range(50,count-window-50,window),key=lambda k:sum(x*x for x in ref[k:k+window]))
            sample=ref[anchor:anchor+window]
            lag=max(range(-48,49),key=lambda d:sum(x*y for x,y in zip(sample,mix[anchor+d:anchor+d+window])))
            x=ref[max(0,-lag):min(count,count-lag)];y=mix[max(0,lag):min(count,count+lag)]
            n=len(x);sx=sum(x);sy=sum(y)
            corr=(sum(a*b for a,b in zip(x,y))-sx*sy/n)/math.sqrt((sum(a*a for a in x)-sx*sx/n)*(sum(b*b for b in y)-sy*sy/n))
            assert corr>.94,(voice,corr,lag)
            correlations[voice].append({'sourceStart':source_at,'correlation':corr,'offsetMilliseconds':lag/48})
    subprocess.run(['ffmpeg','-v','error','-i',str(video),'-f','null','-'],check=True)
    loud=subprocess.run(['ffmpeg','-hide_banner','-i',str(video),'-af','loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json','-f','null','-'],check=True,capture_output=True,text=True).stderr
    (output/'audio-loudness.txt').write_text(loud)
    report={'status':'TECHNICAL_PASS','block':args.block,'frames':frame,'duration':float(meta['format']['duration']),
            'videoSHA256':digest(video),'originalSources':'19/19 preserved','approvedAssets':'All recovered hashes preserved',
            'captionText':'Matches working script after explicit approvals and documented orthographic normalization',
            'voiceMixCorrelations':correlations,'decode':'Complete, no errors','visualReview':'PENDING'}
    (output/'qa.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(report,ensure_ascii=False,indent=2))


if __name__=='__main__':main()
